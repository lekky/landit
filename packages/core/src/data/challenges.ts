/**
 * One live challenge per sport at a time, fortnightly, from 2026-08-31 to
 * 2027-09-12: twenty-seven fourteen-day slots, Monday to Sunday, on the same
 * dates for all three sports.
 *
 * State (`upcoming` / `live` / `past`) is never stored — it is derived from
 * `starts`/`ends` in the rider's timezone by `../rules/challenges.ts`
 * (plan §2.2). `starts` and `ends` are inclusive calendar days, `YYYY-MM-DD`.
 *
 * **The six pre-launch weeks are gone** (Rachid, in chat, 2026-09-11). Weeks
 * 30-35 were the design pack's, transcribed weekly, and ran from 2026-07-20 to
 * 2026-08-30 — before anybody could join. Left in, every new rider's history
 * opened on six finished challenges they could never have done. They are
 * removed here so that a full seed cannot recreate them; the seed never
 * deletes, so the production rows go by hand in the staff portal. Their best
 * themes come back in 2027, with what was wrong with them fixed.
 *
 * Rules every slot keeps, all of them load-bearing:
 *
 * - **Contiguous slots, no overlaps and no gaps.** "One live challenge per
 *   sport" is a hook (`enforceNoChallengeOverlap`), not a column, so the seed
 *   has to be the first thing that respects it — and a *gap* passes that hook
 *   happily while still showing a rider a dead card, which is why
 *   `challenges.test.ts` asserts the slots run back to back.
 * - **Every sport runs the same dates**, so no rider is between slots while
 *   another sport has one live.
 * - **Every slot names tricks that are in the shipped library** (./tricks.ts),
 *   by the library's own names, so a rider reading "a tail tap" has somewhere
 *   in the app to go and find one.
 * - **`reward` names the First Challenge sticker** (issue #76), the one reward
 *   that exists, has a rule, and is awarded server-side on the `challenge_log`
 *   write. `challengeRewardSticker` resolves it by name and a test holds every
 *   slot to it.
 * - **`riders` is empty.** The screen does not render it, and invented
 *   participation is a lie told to children (issue #89).
 * - **Nothing dares anyone into anything.** No heights, no stair sets (#79),
 *   no "counts double", no "film it or it didn't happen". The shapes that
 *   cannot work as a dare are the ones leaned on: landing again a trick the
 *   rider already has, riding with company, a lap of their own park.
 * - **The park, not the road.** To a UK reader a kerb is the edge of a road, so
 *   "On The Kerb" became "Low Ledge". Company means the people a rider came
 *   with — never "whoever was at the park".
 * - **No seasonal framing.** The product is global, so a slot that assumes dark
 *   October evenings is wrong for half the riders reading it. The riding days
 *   it does name fall on the same date everywhere, and each sits inside one
 *   slot: Go Skateboarding Day (21 June, the Monday weeks 25-26 open), Go Scoot
 *   Day (the last Saturday in June, the same slot) and BMX Day (20 July, weeks
 *   29-30). Scooter's and BMX's are grassroots rather than official, so they
 *   are mentioned in passing, never built around. National school-travel weeks
 *   and Road Safety Week were considered and left out: they are one country's,
 *   and they are about roads, which is where these challenges never send
 *   anybody.
 * - **Every hue passes AA under the brief.** The card prints its brief in ink
 *   on the hue; blue (4.18:1), red (4.34:1) and violet (3.42:1) all fell short
 *   of 4.5:1, and `packages/ui-web`'s `contrast.test.ts` measures every slot.
 * - **`week` carries the ISO range** ("Weeks 36-37"), because a slot is two
 *   weeks. Ids carry the year from 2027 (`sc-2027-01`), so a 2027 slot can
 *   never share a slug with a 2026 one.
 */
