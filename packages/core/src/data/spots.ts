/**
 * The spots riders can go to, researched rather than invented (2026-08-18).
 *
 * **Every one of these is a real place, and every coordinate came from a source
 * somebody actually opened** — an OpenStreetMap feature cross-checked against
 * the venue's own page, a council listing, or both. The list this replaces was
 * transcribed from the design prototype, where two of the seven were plausible
 * fiction: a wrong coordinate on this screen sends a child to a place that is
 * not there, which is a different class of defect from a wrong label.
 *
 * **`sports` is researched, not assumed.** Plenty of parks ban BMX because pegs
 * chew concrete, several ban scooters outright, and some famous street spots
 * are protected for skateboarding by name. A sport appears here only where the
 * venue, the council or the protecting agreement says it is allowed.
 *
 * **What this data cannot say.** There is no field for opening hours or for a
 * session timetable, and a good few of these parks are not drop-in-anytime —
 * BMX at BaySixty6 is two evenings a week, and several indoor parks close to
 * the public on weekday afternoons. A rider is told where a place is, never
 * when it is open, so the phone number matters more than it looks.
 *
 * The prototype carried a hard-coded `dist` ("2.4 mi") per spot, measured from
 * a rider who does not exist. Distance is a property of the viewer, not of the
 * spot, so it is not stored: use `distanceMiles` from `../rules/spots.ts`.
 * Every seeded spot is `live`; rider submissions land as `pending` (plan §3).
 */
