/**
 * The world's skateparks — the places on Trucks and Fins' map, matched against
 * OpenStreetMap — to spot rows the seed can write (the owner's call,
 * 2026-09-11, in chat: route B, pages kept out of search, pump tracks count as
 * BMX).
 *
 * **This module is the seeder's and nobody else's**, like `./france.ts`. The
 * rows live in `world.data.ts`, generated by `scripts/import-world.mts`; the
 * app reads the database, and the database is where these become spots.
 *
 * **Everything here is pure**, so each rule has a unit test against hand-made
 * rows and a property test against the real snapshot.
 *
 * ---
 *
 * **Whose data each row is.** Where an OpenStreetMap object sits within 150
 * metres of a park, the point, the name and the address are OpenStreetMap's,
 * under the Open Database Licence — `source: 'osm-tnf'`. Where none does, the
 * row stands on Trucks and Fins' point and name alone — `source: 'tnf'`. On
 * both, the tags, the roof and "gone" come from which of Trucks and Fins' map
 * filters list the park, and that is recorded in the licence column as well
 * (`SPOT_SOURCES` in `@landit/core`). Nothing from Trucks and Fins is prose:
 * it has descriptions and photographs, and none of them is here.
 *
 * **What the data can say, and what it cannot.** A point, a name, a town, and
 * for most parks a filter or two — bowl, mini ramp, pump track, indoor, gone.
 * Nothing about opening hours, and nothing about scooters. So every row goes
 * through `importedSpotSports`: scooter and skate unless a ban is documented,
 * and BMX where the source names it — and, by the owner's call, wherever the
 * park is listed as a pump track, because a pump track is a bike place first.
 * Rows arrive `operating: 'unknown'` unless a source says the park has gone.
 *
 * **The naming rule.** Most names are "*Town* skatepark", which says nothing
 * the card's town line does not already say. A name is *generic* when nothing
 * is left once the words for a facility and the words of its town are taken
 * out — "Rolla skatepark" in Rolla, "Skate Park", "Skateanlage" — and a generic
 * park is called "Skatepark", as a French one is. OpenStreetMap's name is tried
 * before Trucks and Fins', so a mapped name wins. Two parks in one town that
 * would share a name are told apart by an ordinal, in the source's order.
 *
 * **The duplicate rules.** The source map lists a few parks twice, a few
 * metres apart; points within 50 metres of each other are one place, with
 * every filter either copy carried. A place within about 160 metres of a spot
 * already seeded — hand-researched, or from France's census — is that spot,
 * and is dropped: it already has a page somebody checked or a better source.
 */

const OSM_SOURCE = SPOT_SOURCES['osm-tnf'];
const TNF_SOURCE = SPOT_SOURCES.tnf;

/** `spots.name` is `max: 80` (`1786838400_init_collections.js`). */
const NAME_MAX = 80;
/** The name a generic park gets; the town disambiguates on the card. */
const GENERIC_NAME = 'Skatepark';
/** The source listing one park twice: points this close are one place. */
const SAME_PLACE_MILES = 50 / 1609.344;
/** A place this close to a spot already seeded is that spot — France's radius. */
const EXISTING_RADIUS_MILES = 0.1;

