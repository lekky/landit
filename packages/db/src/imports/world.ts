/**
 * The words of a name, lowercase with accents folded — in any script, so a
 * Cyrillic or Japanese name has words too (the census's fold in `./france.ts`
 * keeps Latin letters only).
 */
export function nameWords(text: string): string[] {
  return text
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .split(/[^\p{L}\p{N}]+/u)
    .filter(Boolean);
}

/**
 * The list folded exactly as a name is, so "Скейтпарк" — whose й a fold splits
 * into и and a mark — is found by the same words it is compared with.
 */
const WORLD_FACILITY_WORDS = new Set(FACILITY_WORD_LIST.flatMap((word) => nameWords(word)));

function isFacilityWord(word: string): boolean {
  if (WORLD_FACILITY_WORDS.has(word) || /^\d+$/.test(word)) return true;
  // A Latin word goes through the census's list as well: "park", "the", "de".
  return /^[a-z0-9]+$/.test(word) && isGenericName(word);
}

/**
 * Does this name say *which* place, or only what kind and which town?
 *
 * Generic: "Rolla skatepark" in Rolla, "Skate Park", "Skateanlage",
 * "Community Skatepark". Not generic: "Finlathen skatepark" in Dundee,
 * "Southbank Undercroft", "駒沢公園スケートパーク".
 */
export function isGenericWorldName(name: string, town: string): boolean {
  const townWords = new Set(nameWords(town));
  return nameWords(name)
    .filter((word) => !townWords.has(word))
    .every(isFacilityWord);
}

/**
 * A kept name, tidied: shouting and whispering re-cased as the census's are,
 * and the lowercase "skatepark" or "pumptrack" the source map appends to its
 * names given a capital — "Finlathen skatepark" → "Finlathen Skatepark".
 */
export function tidyName(name: string): string {
  return recaseName(name.replace(/\s+/g, ' ').trim()).replace(
    /\b(skatepark|pumptrack)\b/g,
    (word) => word.charAt(0).toUpperCase() + word.slice(1),
  );
}

/* ------------------------------------------------------------ places -- */

/** One or more source rows that are one place, the one it is named from first. */
export interface WorldPlace {
  readonly rows: readonly WorldSourceRow[];
  readonly lat: number;
  readonly lng: number;
  readonly town: string;
  /** ISO 3166-1 alpha-2. */
  readonly country: string;
  /** Every filter any of the rows was listed under. */
  readonly flags: number;
  /** Every OpenStreetMap fact any matched row carried. */
  readonly osmBits: number;
  /** Is the place's point and name OpenStreetMap's? */
  readonly matched: boolean;
}

/** Rows with an OpenStreetMap match first, then the source's order. */
const byStrength = (a: WorldSourceRow, b: WorldSourceRow): number =>
  (a[1] ? 0 : 1) - (b[1] ? 0 : 1) || a[0] - b[0];

const CELL = 0.001;
const cellKey = (lat: number, lng: number, size: number): string =>
  `${Math.floor(lat / size)},${Math.floor(lng / size)}`;

/** How many cells either side cover `size` degrees of latitude at this latitude. */
const lngRings = (lat: number): number =>
  Math.ceil(1 / Math.max(0.15, Math.cos((lat * Math.PI) / 180)));

/**
 * Rows within 50 metres of one another are one place. Transitive, so three
 * copies in a line collapse to one; in the source's order, so the same
 * snapshot always gives the same places.
 */
export function collapseWorld(rows: readonly WorldSourceRow[]): readonly WorldPlace[] {
  const sorted = [...rows].sort((a, b) => a[0] - b[0]);
  const parent = sorted.map((_, i) => i);
  const find = (i: number): number => {
    while (parent[i] !== i) {
      parent[i] = parent[parent[i]!]!;
      i = parent[i]!;
    }
    return i;
  };

  const cells = new Map<string, number[]>();
  sorted.forEach((row, i) => {
    const key = cellKey(row[2], row[3], CELL);
    const cell = cells.get(key);
    if (cell) cell.push(i);
    else cells.set(key, [i]);
  });

  sorted.forEach((row, i) => {
    const cy = Math.floor(row[2] / CELL);
    const cx = Math.floor(row[3] / CELL);
    const rings = lngRings(row[2]);
    for (let y = cy - 1; y <= cy + 1; y += 1) {
      for (let x = cx - rings; x <= cx + rings; x += 1) {
        for (const j of cells.get(`${y},${x}`) ?? []) {
          if (j <= i) continue;
          const other = sorted[j]!;
          const d = distanceMiles({ lat: row[2], lng: row[3] }, { lat: other[2], lng: other[3] });
          if (d <= SAME_PLACE_MILES) parent[find(j)] = find(i);
        }
      }
    }
  });

  const groups = new Map<number, WorldSourceRow[]>();
  sorted.forEach((row, i) => {
    const root = find(i);
    const group = groups.get(root);
    if (group) group.push(row);
    else groups.set(root, [row]);
  });

  return [...groups.values()]
    .map((group) => {
      const members = [...group].sort(byStrength);
      const lead = members[0]!;
      return {
        rows: members,
        lat: lead[2],
        lng: lead[3],
        town: lead[10],
        country: lead[11],
        flags: members.reduce((all, row) => all | row[6], 0),
        osmBits: members.reduce((all, row) => all | row[7], 0),
        matched: lead[1] !== '',
      };
    })
    .sort((a, b) => a.rows[0]![0] - b.rows[0]![0]);
}

/** Every existing spot, bucketed by about a kilometre, for the proximity rule. */
function existingIndex(existing: readonly Spot[]): Map<string, Spot[]> {
  const index = new Map<string, Spot[]>();
  for (const spot of existing) {
    const key = cellKey(spot.lat, spot.lng, 0.01);
    const cell = index.get(key);
    if (cell) cell.push(spot);
    else index.set(key, [spot]);
  }
  return index;
}

function nearExisting(place: WorldPlace, index: Map<string, Spot[]>): boolean {
  const cy = Math.floor(place.lat / 0.01);
  const cx = Math.floor(place.lng / 0.01);
  const rings = lngRings(place.lat);
  for (let y = cy - 1; y <= cy + 1; y += 1) {
    for (let x = cx - rings; x <= cx + rings; x += 1) {
      for (const spot of index.get(`${y},${x}`) ?? []) {
        const d = distanceMiles({ lat: place.lat, lng: place.lng }, spot);
        if (d <= EXISTING_RADIUS_MILES) return true;
      }
    }
  }
  return false;
}

/* --------------------------------------------------------------- names -- */

/**
 * What a place is called before any collision is resolved: the first name, in
 * strength order and OpenStreetMap's before Trucks and Fins', that says which
 * place it is and fits the column.
 */
export function baseName(place: WorldPlace): string {
  for (const row of place.rows) {
    for (const candidate of [row[4], row[5]]) {
      if (!candidate || isGenericWorldName(candidate, place.town)) continue;
      const name = tidyName(candidate);
      if (name.length <= NAME_MAX) return name;
    }
  }
  return GENERIC_NAME;
}

/**
 * Every name unique within its town — against the spots already seeded as
 * well as each other, because the seed's key is name-plus-town and a clash
 * would find the other spot and skip this one. The first place keeps the bare
 * name; later ones count up.
 */
export function nameWorldSpots(
  places: readonly WorldPlace[],
  existing: readonly Pick<Spot, 'name' | 'town'>[] = [],
): readonly string[] {
  const taken = new Map<string, Set<string>>();
  const inTown = (town: string): Set<string> => {
    let names = taken.get(town);
    if (!names) {
      names = new Set();
      taken.set(town, names);
    }
    return names;
  };
  for (const spot of existing) inTown(spot.town).add(spot.name);

  return places.map((place) => {
    const used = inTown(place.town);
    const base = baseName(place);
    let name = base;
    for (let n = 2; used.has(name); n += 1) {
      const suffix = ` ${n}`;
      name =
        base.length + suffix.length <= NAME_MAX ? `${base}${suffix}` : `${GENERIC_NAME}${suffix}`;
    }
    used.add(name);
    return name;
  });
}

/* ------------------------------------------------------------ the rest -- */

/**
 * The filters that are features, as the tags `SPOT_FEATURES` explains, in the
 * catalogue's order. "Concrete Park" is the type every outdoor park already
 * has; "Built in the 70s" is history rather than something to ride.
 */
const FLAG_TAGS: readonly (readonly [TnfFlag, string])[] = [
  ['bowl', 'Bowl'],
  ['miniRamp', 'Mini'],
  ['vert', 'Vert'],
  ['halfpipe', 'Halfpipe'],
  ['snakeRun', 'Snake run'],
  ['fullPipe', 'Full pipe'],
  ['pumpTrack', 'Pump track'],
  ['diy', 'DIY'],
];

const FEATURE_ORDER = new Map(SPOT_FEATURE_LIST.map((feature, i) => [feature.id, i]));

export function tagsFor(flags: number): string[] {
  return FLAG_TAGS.filter(([flag]) => flags & TNF_FLAG[flag])
    .map(([, tag]) => tag)
    .sort(
      (a, b) =>
        (FEATURE_ORDER.get(spotFeatureId(a)) ?? Infinity) -
        (FEATURE_ORDER.get(spotFeatureId(b)) ?? Infinity),
    );
}

/** One of `SPOT_TYPES`: under a roof, a street spot, or the outdoor park most are. */
export function typeFor(place: WorldPlace, indoor: boolean): string {
  if (indoor) return 'Indoor park';
  if (place.flags & TNF_FLAG.streetSpot) return 'Street spot';
  return 'Concrete';
}

const BMX_WORD = /\bbmx\b/i;

/**
 * What the sources say about who may ride, for `importedSpotSports`: BMX where
 * OpenStreetMap's `sport` tag or either name says BMX, and wherever the park is
 * listed as a pump track (the owner's call, 2026-09-11, in chat). Nothing here
 * is ever a ban — neither source records one.
 */
export function sportsEvidence(place: WorldPlace): ImportedSportsEvidence {
  const named = place.rows.some((row) => BMX_WORD.test(row[4]) || BMX_WORD.test(row[5]));
  const pumpTrack = (place.flags & TNF_FLAG.pumpTrack) !== 0;
  const tagged = (place.osmBits & OSM_BIT.bmx) !== 0;
  return { bmx: named || pumpTrack || tagged };
}

/** The country name the spots data spells, for an alpha-2 code. */
export function countryName(code: string): string {
  return SPOT_COUNTRY_BY_CODE[code] ?? COUNTRIES[code] ?? code;
}

/**
 * The snapshot as spots. Pure: same snapshot, same existing spots, same rows
 * in the same order.
 *
 * `existing` defaults to what the seed writes before this table — the
 * hand-researched `SPOTS` and France's census — and is a parameter so the
 * tests can prove the rules without depending on either.
 */
export function worldSpots(
  rows?: readonly WorldSourceRow[],
  existing?: readonly Spot[],
): readonly Spot[] {
  if (rows === undefined && existing === undefined) {
    return (snapshotSpots ??= mapWorld(WORLD_SOURCE_ROWS, seededBefore()));
  }
  return mapWorld(rows ?? WORLD_SOURCE_ROWS, existing ?? seededBefore());
}

/** What the seed writes before this table: the researched spots, then France's. */
const seededBefore = (): readonly Spot[] => [...(SPOTS as readonly Spot[]), ...franceSpots()];

/**
 * The snapshot, mapped once per process. Every table in a seed plan and every
 * test that builds one asks for the same twenty-five thousand rows, and a plan
 * is built many times over in a test run; the answer never changes, because
 * everything it is computed from is a constant.
 */
let snapshotSpots: readonly Spot[] | undefined;

function mapWorld(rows: readonly WorldSourceRow[], existing: readonly Spot[]): readonly Spot[] {
  const index = existingIndex(existing);
  const places = collapseWorld(rows).filter((place) => !nearExisting(place, index));
  const names = nameWorldSpots(places, existing);
  return places.map((place, i) => {
    const lead = place.rows[0]!;
    const indoor = (place.flags & TNF_FLAG.indoor) !== 0 || (place.osmBits & OSM_BIT.covered) !== 0;
    const closed = (place.flags & TNF_FLAG.closed) !== 0 || (place.osmBits & OSM_BIT.closed) !== 0;
    const source = place.matched ? OSM_SOURCE : TNF_SOURCE;
    return {
      name: names[i]!,
      town: place.town,
      country: countryName(place.country),
      type: typeFor(place, indoor),
      lat: place.lat,
      lng: place.lng,
      sports: importedSpotSports(sportsEvidence(place)),
      tags: tagsFor(place.flags),
      status: 'live',
      ...(lead[8] ? { address: lead[8] } : {}),
      ...(lead[9] ? { phone: lead[9] } : {}),
      indoor,
      operating: closed ? 'closed' : 'unknown',
      source: source.id,
      licence: source.licence,
    };
  });
}
